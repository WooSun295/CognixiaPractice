from bson import ObjectId
from helpers.helper import currTime
from database.database import client

from services.transaction_services import createTxnDB

db = client["simple_bank_db"]

accCol = db["Accounts"]

def getAccountsDB():
    res = list(accCol.find())
    for r in res:
        r["_id"] = str(r["_id"])
        r["userId"] = str(r["userId"])

    return res
    
def getAccountDB(accountId: str):
    if not ObjectId.is_valid(accountId):
        return False
    res = accCol.find_one({"_id": ObjectId(accountId)})
    if res:
        res["_id"] = str(res["_id"])
        res["userId"] = str(res["userId"])

    return res

